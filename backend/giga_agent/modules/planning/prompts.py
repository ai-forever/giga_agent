"""Системные инструкции модуля planning.

Подмешиваются в общий system prompt через PlanningModule.get_instructions.
NORMAL — всегда. PLAN_MODE — только когда state["mode"] == "plan".
"""

NORMAL_INSTRUCTIONS = """\
## Планирование задач

Для многошаговой задачи (3+ нетривиальных шага) план задаётся ТОЛЬКО вызовом \
`update_plan` — это и есть план, который видит пользователь. ВСЕГДА вызывай \
`update_plan` ПЕРЕД началом работы. Не описывай шаги текстом вместо вызова тула.

ЯЗЫК: `title` каждого пункта пиши на языке запроса пользователя. Русский запрос \
— русские пункты, не английские.

ВАЖНО: не пиши план прозой в тексте сообщения. Чеклист из `update_plan` уже \
показывает пункты. Никаких «План действий:» и нумерованных списков шагов в \
тексте — это дублирование. Допустима ровно одна короткая вводная строка \
(например, «Начинаю» или «Соберу за пару шагов»), без перечисления пунктов.

Правила:
- Держи ровно один пункт в статусе `in_progress` за раз.
- Обновляй статусы сразу по завершении шага, не батчами в конце.
- Если шаг оказался не нужен — ставь `skipped` и в `note` коротко объясни почему.
- Если реальность разошлась с планом — перепиши список через `update_plan` заново, \
не притворяйся, что старый план ещё в силе.
- При новом, не связанном со старым планом запросе — очисти план: `update_plan([])`.
- Не бросай план молча. Если шаг не получается выполнить доступными \
инструментами — пометь его `skipped` с краткой причиной в `note` и иди дальше \
(или заверши, явно объяснив, чего не хватило). Не оставляй шаг висеть в \
`in_progress`.
- Формулируй пункты плана на языке пользователя.

Не используй план для простых однотактовых запросов — это лишний шум.
"""

