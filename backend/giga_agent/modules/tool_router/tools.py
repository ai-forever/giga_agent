"""Escape-hatch тул для динамического роутера.

Если роутер не подгрузил нужный инструмент, модель вызывает `request_tools`
с описанием намерения. Сам тул ничего не делает с системой — он лишь
фиксирует намерение в истории диалога; на следующем шаге роутер увидит этот
вызов (его аргументы) и подгрузит соответствующий тулсет.
"""

from __future__ import annotations

from langchain_core.tools import tool

from giga_agent.core.agent.tool_policy import ToolEffect, tool_extras


@tool(parse_docstring=True, extras=tool_extras(ToolEffect.READ))
async def request_tools(intent: str) -> str:
    """Запросить подключение инструментов под конкретную задачу.

    Вызови этот инструмент, если нужного тебе инструмента нет в текущем списке.
    Опиши, что хочешь сделать (например "работа с задачами в Трекере" или
    "выполнить код на Python"). На следующем шаге появятся подходящие
    инструменты.

    Args:
        intent: Короткое описание задачи или нужных инструментов на русском.
    """
    return (
        f"Подбираю инструменты под задачу: {intent}. "
        "Повтори своё действие — нужные инструменты теперь доступны."
    )
