def _extract_final_report(result_state: dict) -> str:
    if "files" in result_state and "/final_report.md" in result_state["files"]:
        final_report = result_state["files"]["/final_report.md"]
        if isinstance(final_report, dict):
            return "\n".join(final_report['content'])
        else:
            return final_report
    messages = result_state.get("messages") or []
    if messages:
        return messages[-1].content
    return ""


@tool
async def researcher_agent(question: str, runtime: ToolRuntime):
    """Проводит исследование и создает на его основе отчёт по запросу пользователя"""
    factory = await get_session_factory()
    async with factory() as session:
        user = await get_current_user_from_runtime(runtime, session=session)
        llm = await resolve_user_llm(user, session=session)
    llm = llm.bind(timeout=120).with_config(tags=["nostream"])
    last_mes = filter_tool_calls(runtime.state["messages"][-1])
    result_state = {}

    async def internet_search(
        query: str,
        max_results: int = 10,
        topic: Literal["general", "news", "finance"] = "general",
        include_raw_content: bool = False,
    ):
        """Функция поиска в интернете"""
        _ = (max_results, topic, include_raw_content)
        factory = await get_session_factory()
        async with factory() as session:
            current_user = await get_current_user_from_runtime(runtime, session=session)
            search_engine = await resolve_user_search_engine(
                current_user,
                session=session,
            )
        result = await search_engine.search([query])
        return "\n\n".join(normalize_search_result(item) for item in result)

    research_sub_agent = {
        "name": "research-agent",
        "description": (
            "Используется для более глубокого исследования вопросов. "
            "Давайте этому исследователю только одну тему за раз. "
            "Не передавайте ему несколько подвопросов. "
            "Вместо этого следует разбить большую тему на необходимые компоненты, "
            "а затем вызывать нескольких исследовательских агентов, "
            "по одному для каждого подвопроса."
        ),
        "system_prompt": sub_research_prompt,
        "tools": [internet_search],
    }

    critique_sub_agent = {
        "name": "critique-agent",
        "description": (
            "Используется для критики итогового отчёта. "
            "Предоставьте этому агенту информацию о том, как вы хотите, "
            "чтобы он критиковал отчёт."
        ),
        "system_prompt": sub_critique_prompt,
    }

    agent = create_deep_agent(
        model=llm,
        tools=[internet_search],
        system_prompt=research_instructions,
        subagents=[critique_sub_agent, research_sub_agent],
    ).with_config({"recursion_limit": 1000})
    config = runtime.config.copy()
    config['recursion_limit'] = 10000
    async for chunk in agent.astream(
        input={
            "messages": runtime.state["messages"][:-1]
            + [
                last_mes,
                ("user", question),
            ],
        },
        stream_mode=["values"],
        config=config,
    ):
        if chunk[0] == "values":
            result_state = chunk[1]
    final_report = _extract_final_report(result_state)

    if not final_report:
        return build_tool_message(
            runtime,
            tool_name="researcher_agent",
            payload={
                "message": "Отчёт не сгенерировался, попробуй вызвать агента ещё раз.",
            },
        )

    prefix = resolve_upload_prefix(runtime)
    uploaded = await upload_files_for_runtime_user(
        runtime,
        files=[
            {
                "file_name": f"{prefix}/research_result.md",
                "file_type": "text",
                "content": final_report.encode("utf-8"),
            }
        ],
    )
    file = uploaded[0]

    return build_tool_message(
        runtime,
        tool_name="researcher_agent",
        payload={
            "message": (
                f"В результате выполнения был получен следующий отчёт и "
                f"сохранен в файле: {file.sandbox_path}. "
                f"НЕ ВЫВОДИ отчет сам, вместо этого покажи его пользователю через вложение "
                f'"![alt-описание](attachment:{file.sandbox_path})"'
            ),
            "text": final_report,
        },
        attachments=uploaded,
    )
