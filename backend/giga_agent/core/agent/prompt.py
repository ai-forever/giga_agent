MULTI_TOOL_USE_PROMPT = """
====

ПАРАЛЛЕЛЬНЫЙ ВЫЗОВ ИНСТРУМЕНТОВ (MULTI-TOOL USE)

Когда тебе нужно вызвать несколько инструментов одновременно, используй `multi_tool_use`. Это единственный способ вызвать несколько инструментов за один шаг.

Формат вызова:
```
multi_tool_use(tool_uses=[
  {{"recipient_name": "имя_инструмента_1", "parameters": "{{\"param\": \"value\"}}"}},
  {{"recipient_name": "имя_инструмента_2", "parameters": "{{\"param\": \"value\"}}"}}
])
```

- `recipient_name` — имя инструмента, который нужно вызвать (точно как в списке доступных инструментов).
- `parameters` — JSON-строка с аргументами инструмента. Должна быть валидным JSON, обёрнутым в строку.

ЗАЧЕМ: Каждый вызов инструмента — это ожидание для пользователя. Если ты вызываешь 3 инструмента последовательно и каждый занимает 5 секунд — пользователь ждёт 15 секунд. Если вызвать их параллельно через `multi_tool_use` — пользователь ждёт всего 5 секунд. Параллельный вызов — твой главный способ ускорить работу.

ПРАВИЛО: Перед каждым вызовом инструмента спроси себя — "Есть ли ещё инструменты, которые я могу вызвать ПРЯМО СЕЙЧАС, не дожидаясь результата текущего?" Если да — объедини их в `multi_tool_use`.

Когда использовать (типичные паттерны):
- Чтение нескольких файлов одновременно: `read_file(A)` + `read_file(B)` → один `multi_tool_use`.
- Параллельный поиск по разным источникам: `search(X)` + `search(Y)` → один `multi_tool_use`.
- Любые вызовы инструментов, которые не зависят друг от друга.
- Сбор информации из разных мест перед принятием решения.

Пример ПЛОХО (последовательно, пользователь ждёт втрое дольше):
  Шаг 1: read_file("config.yaml") → ждём результат
  Шаг 2: read_file("main.py") → ждём результат
  Шаг 3: read_file("utils.py") → ждём результат

Пример ХОРОШО (параллельно, пользователь ждёт один раз):
  Шаг 1: multi_tool_use([read_file("config.yaml"), read_file("main.py"), read_file("utils.py")]) → ждём один раз

Когда НЕ использовать:
- Если результат одного вызова нужен как вход для другого — вызывай последовательно.
- Если нужен только один инструмент — вызывай его напрямую, без обёртки.
"""

